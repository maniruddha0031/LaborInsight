#!/usr/bin/env node
/*
 * build-snapshot.js — pre-compute a registered dataset so the portal opens on its analysis instantly.
 *
 *   node tools/build-snapshot.js <dataset-id>        (id from datasets/manifest.json)
 *
 * Runs the same engine as the browser on the dataset's ZIP part(s) and writes, as plain <script> files
 * (so it also works when index.html is opened straight from disk):
 *   datasets/<id>.snapshot/result.js      UI payload + small drill-down lists
 *   datasets/<id>.snapshot/emp<N>.js      employee (GEID) drill-downs, sharded by GEID hash
 *   datasets/<id>.snapshot/stores.js      store drill-downs
 * and records the snapshot in manifest.json + manifest.js. Re-run after changing the dataset or the engine.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
global.self = global;
global.fflate = require(path.join(ROOT, 'lib', 'fflate.min.js'));
const ENGINE = require(path.join(ROOT, 'js', 'engine', 'files.json'));
for (const f of ENGINE) require(path.join(ROOT, 'js', 'engine', f));
const LCI = global.LCI;

// Round floats to keep files small; NaN/Infinity become null (the UI treats null as "no value").
const replacer = (k, v) => (typeof v === 'number' ? (isFinite(v) ? (Number.isInteger(v) ? v : Math.round(v * 10000) / 10000) : null) : v instanceof Set ? v.size : v);
const wrap = (id, part, data) => `/* generated by tools/build-snapshot.js — do not edit */\nwindow.LCI_SNAPSHOT_LOAD(${JSON.stringify(id)},${JSON.stringify(part)},${JSON.stringify(data, replacer)});\n`;

async function main() {
  const id = process.argv[2];
  const mfPath = path.join(ROOT, 'datasets', 'manifest.json');
  const mf = JSON.parse(fs.readFileSync(mfPath, 'utf8'));
  const ds = (mf.datasets || []).find((d) => d.id === id);
  if (!ds) { console.error(`Dataset "${id}" is not in datasets/manifest.json`); process.exit(2); }
  const cfg = { name: ds.id, label: ds.label || ds.id, excludeStores: ds.excludeStores || [], rules: ds.rules || {} };
  const ing = new LCI.Ingestor(cfg);
  const t0 = Date.now();
  for (const f of ds.files) {
    const file = path.join(ROOT, 'datasets', f);
    async function* chunks() { for await (const c of fs.createReadStream(file, { highWaterMark: 1 << 20 })) yield new Uint8Array(c.buffer, c.byteOffset, c.length); }
    await LCI.pipeline.readZip(chunks(), ing, null);
  }
  const { result, ctx } = LCI.pipeline.analyse(ing, cfg, ({ msg }) => process.stderr.write('  ' + msg + '\n'));
  const engineHash = crypto.createHash('sha256').update(ENGINE.map((f) => fs.readFileSync(path.join(ROOT, 'js', 'engine', f))).join('')).digest('hex').slice(0, 12);
  result.meta.snapshot = { generatedAt: new Date().toISOString(), engine: engineHash, source: ds.files };
  const snap = LCI.present.snapshot(ctx, result, 64);

  const dir = path.join(ROOT, 'datasets', id + '.snapshot');
  // Empty the folder rather than deleting it: synced folders (OneDrive) often hold a lock on the directory.
  fs.mkdirSync(dir, { recursive: true });
  for (const f of fs.readdirSync(dir)) fs.rmSync(path.join(dir, f), { recursive: true, force: true });
  let bytes = 0;
  const write = (name, part, data) => { const s = wrap(id, part, data); fs.writeFileSync(path.join(dir, name), s); bytes += s.length; };
  write('result.js', 'result', { result: snap.result, inline: snap.inline, empShards: snap.empShards });
  for (const k in snap.shards) write(k + '.js', k, snap.shards[k]);
  // Portable model (deflated, base64) so store/date filters can re-run the engine in the browser.
  const pm = LCI.scope.packModel(ctx.M0);
  pm.chunks.forEach((c, i) => write(`model${i}.js`, `model${i}`, c));

  // Engine bundle: engine + worker as one string, started as a Blob worker when the page is opened from disk.
  const src = [fs.readFileSync(path.join(ROOT, 'lib', 'fflate.min.js'), 'utf8')]
    .concat(ENGINE.map((f) => fs.readFileSync(path.join(ROOT, 'js', 'engine', f), 'utf8')))
    .concat([fs.readFileSync(path.join(ROOT, 'js', 'worker.js'), 'utf8')]).join('\n;\n');
  fs.writeFileSync(path.join(ROOT, 'js', 'engine.bundle.js'),
    `/* generated by tools/build-snapshot.js (engine ${engineHash}) — do not edit; re-run the tool after engine changes */\nwindow.LCI_ENGINE_BUNDLE = ${JSON.stringify({ engine: engineHash, src })};\n`);

  ds.snapshot = { dir: id + '.snapshot', empShards: snap.empShards, modelParts: pm.chunks.length, generatedAt: result.meta.snapshot.generatedAt, engine: engineHash };
  fs.writeFileSync(mfPath, JSON.stringify(mf, null, 2) + '\n');
  fs.writeFileSync(path.join(ROOT, 'datasets', 'manifest.js'), '/* generated from manifest.json by tools/build-snapshot.js — lets index.html read the manifest when opened from disk */\nwindow.LCI_MANIFEST = ' + JSON.stringify(mf, null, 2) + ';\n');
  console.log(`model: ${(pm.rawBytes / 1048576).toFixed(1)} MiB JSON → ${(pm.zBytes / 1048576).toFixed(1)} MiB deflated in ${pm.chunks.length} part(s)`);
  console.log(`snapshot ${id}: ${Object.keys(snap.shards).length + 1 + pm.chunks.length} files, ${(bytes / 1048576).toFixed(1)} MiB, engine ${engineHash}, ${((Date.now() - t0) / 1000).toFixed(0)} s`);
}
main().catch((e) => { console.error(e); process.exit(1); });
